# test-report-contrast.sh - count axe color-contrast violations in the generated
# HTML reports (risk, security, NOTICE, conformance), in the light and the dark
# colour scheme.
#
# The reports are built hermetically from tests/fixtures/report-contrast, at the
# size of a real scan: 72 components, 374 findings over five severities, kernel
# and no-CVE advisories, a licence that needs review, a malicious package, model
# assessments, a firmware scope note, and an AI SBOM with the G7 tables. No
# network, Docker or vulnerability database is needed:
#   - a stub `trivy` returns the canned result;
#   - a stub `curl` answers the EPSS and CISA KEV lookups from epss.json and
#     kev.json, so SECURITY_ENRICH stays on and the EPSS column, the KEV badge
#     and the KEV pill are rendered and checked;
#   - grype is switched off (DEEP_CVE=false).
# The fixtures are generated by tests/report-contrast/make-fixtures.sh.
#
# Usage: tests/test-report-contrast.sh [--max-risk N] [--max-security N]
#                                      [--max-notice N] [--max-conformance N]
#   Without --max-* the run only reports the counts (always exits 0 unless the
#   reports or the browser cannot be set up). With a --max-* bound, a count
#   above it fails the run. CI passes 0 for all four.
# REPORT_CONTRAST_KEEP=<dir> keeps the generated reports in <dir>.
# Needs: bash, jq, node, and `npm ci` done in docker/web/frontend plus
#   `npx playwright install chromium`.
set -e

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FRONTEND="$ROOT/docker/web/frontend"
FIX="$ROOT/tests/fixtures/report-contrast"

MAX_RISK=""; MAX_SECURITY=""; MAX_NOTICE=""; MAX_CONFORMANCE=""
while [ $# -gt 0 ]; do
    case "$1" in
        --max-risk) MAX_RISK="$2"; shift 2 ;;
        --max-security) MAX_SECURITY="$2"; shift 2 ;;
        --max-notice) MAX_NOTICE="$2"; shift 2 ;;
        --max-conformance) MAX_CONFORMANCE="$2"; shift 2 ;;
        *) echo "unknown option: $1 (see the usage header of $0)" >&2; exit 2 ;;
    esac
done

for tool in jq node; do
    command -v "$tool" >/dev/null 2>&1 || { echo "missing $tool; install it and retry" >&2; exit 2; }
done
if [ ! -d "$FRONTEND/node_modules/@axe-core/playwright" ]; then
    echo "frontend dependencies missing: run 'npm ci' in docker/web/frontend" >&2
    exit 2
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/bin" "$WORK/out"
cat > "$WORK/bin/trivy" <<'STUB'
#!/bin/bash
out=""; prev=""
for a in "$@"; do [ "$prev" = "--output" ] && out="$a"; prev="$a"; done
cp "$RC_TRIVY_FIXTURE" "$out"
STUB
chmod +x "$WORK/bin/trivy"

cat > "$WORK/bin/curl" <<'STUB'
#!/bin/bash
# Answers the two enrichment lookups from fixtures; any other URL fails like an
# unreachable host would.
for a in "$@"; do
    case "$a" in
        *api.first.org*|*epss*) cat "$RC_EPSS_FIXTURE"; exit 0 ;;
        *known_exploited*) cat "$RC_KEV_FIXTURE"; exit 0 ;;
    esac
done
exit 7
STUB
chmod +x "$WORK/bin/curl"

export RC_TRIVY_FIXTURE="$FIX/trivy.json" RC_EPSS_FIXTURE="$FIX/epss.json" RC_KEV_FIXTURE="$FIX/kev.json"
export PATH="$WORK/bin:$PATH"
export SECURITY_ENRICH=true DEEP_CVE=false
P="$WORK/out/sample_1.0"

# A supplier SBOM under review: conformance fails, every section of the risk
# report is present.
bash "$ROOT/docker/lib/validate-sbom.sh" "$FIX/sbom.json" "$P" sample >/dev/null
bash "$ROOT/docker/lib/scan-security.sh" "$FIX/sbom.json" "$P" sample >/dev/null
bash "$ROOT/docker/lib/generate-notice.sh" "$FIX/sbom.json" "$P" sample >/dev/null 2>&1
cp "$FIX/risk-bom.json" "${P}_bom.json"
bash "$ROOT/docker/lib/generate-risk-report.sh" "$P" sample ANALYZE >/dev/null
for f in risk-report security NOTICE conformance; do
    [ -s "${P}_$f.html" ] || { echo "report not generated: ${P}_$f.html" >&2; exit 1; }
done
# The enrichment must really have run, or the EPSS/KEV colours go unchecked.
grep -q 'class="kevbadge"' "${P}_security.html" \
    || { echo "the security report has no KEV badge: the stub curl was not used" >&2; exit 1; }
grep -q '<th>EPSS</th>' "${P}_security.html" \
    || { echo "the security report has no EPSS column" >&2; exit 1; }

# A firmware scan: the same data plus the analysis-scope note.
F="$WORK/out/fw_1.0"
for ext in conformance.json security.json NOTICE.txt; do cp "${P}_$ext" "${F}_$ext"; done
jq '.metadata.component.properties = [
      {name:"bomlens:firmware:input-bytes",value:"33554432"},
      {name:"bomlens:firmware:unknown-top-level-percent",value:"12.5"},
      {name:"bomlens:firmware:unknown-bytes",value:"4194304"},
      {name:"bomlens:firmware:extraction-failed",value:"2"},
      {name:"bomlens:firmware:extraction-failed-formats",value:"squashfs,ubi"},
      {name:"bomlens:firmware:encrypted-regions",value:"1"},
      {name:"bomlens:firmware:missing-extractors",value:"sasquatch"}]' \
    "$FIX/risk-bom.json" > "${F}_bom.json"
bash "$ROOT/docker/lib/generate-risk-report.sh" "$F" sample FIRMWARE >/dev/null
[ -s "${F}_risk-report.html" ] || { echo "report not generated: ${F}_risk-report.html" >&2; exit 1; }

# An AI SBOM: the G7 cluster, licence and check tables.
A="$WORK/out/ai_1.0"
bash "$ROOT/docker/lib/validate-sbom.sh" "$ROOT/tests/fixtures/aibom-owasp-1_7.json" "$A" aimodel >/dev/null
[ -s "${A}_conformance.html" ] || { echo "report not generated: ${A}_conformance.html" >&2; exit 1; }

# REPORT_CONTRAST_KEEP=<dir> keeps the generated reports there, to look at them.
if [ -n "${REPORT_CONTRAST_KEEP:-}" ]; then
    mkdir -p "$REPORT_CONTRAST_KEEP" && cp "$WORK"/out/*.html "$REPORT_CONTRAST_KEEP"/
fi

OUT="$WORK/axe.out"
node "$ROOT/tests/report-contrast/axe-report-contrast.mjs" "$FRONTEND" \
    "${P}_risk-report.html" "${F}_risk-report.html" "${P}_security.html" "${P}_NOTICE.html" \
    "${P}_conformance.html" "${A}_conformance.html" \
    | tee "$OUT"
SUMMARY="$(sed -n 's/^SUMMARY //p' "$OUT")"
[ -n "$SUMMARY" ] || { echo "axe produced no summary" >&2; exit 1; }

# Sum over every report of a kind (the file name ends in _<kind>.html).
count() { echo "$SUMMARY" | jq -r --arg k "_$1.html" '[to_entries[] | select(.key | endswith($k)) | .value] | add'; }
RISK=$(count risk-report); SEC=$(count security); NOT=$(count NOTICE); CONF=$(count conformance)

TABLE="| Report | color-contrast violations |
|---|---|
| risk-report | $RISK |
| security | $SEC |
| NOTICE | $NOT |
| conformance | $CONF |"
echo
echo "$TABLE"
if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
    { echo "### Report color-contrast (axe)"; echo; echo "$TABLE"; } >> "$GITHUB_STEP_SUMMARY"
fi

rc=0
check() { # name count max
    if [ -n "$3" ] && [ "$2" -gt "$3" ]; then
        echo "FAIL: $1 has $2 contrast violations, limit $3" >&2
        rc=1
    fi
}
check risk "$RISK" "$MAX_RISK"
check security "$SEC" "$MAX_SECURITY"
check notice "$NOT" "$MAX_NOTICE"
check conformance "$CONF" "$MAX_CONFORMANCE"
exit "$rc"
