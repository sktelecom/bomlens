/**
 * Pure parser/emitter for the shared token file. Reads the colour and
 * font-size custom properties out of src/index.css (the single source of
 * truth) and renders `bomlens-tokens.css`. No variable name is hardcoded:
 * whatever index.css declares in `:root` / `.dark` is followed automatically.
 *
 * A declaration is exported when it is
 *   - a colour: a bare channel triplet ("234 88 12", "349 100% 46%"), a hex
 *     literal, or an rgb()/rgba()/hsl()/hsla() call; or
 *   - a font size: a `--font-size-*`, `--fs-*` or `--text-*` property holding a
 *     CSS length (px/rem/em).
 * Radius, shadow, easing and duration tokens are not exported.
 */

const COLOUR_VALUE = new RegExp(
  [
    String.raw`^-?\d+(?:\.\d+)?%?(?:\s+-?\d+(?:\.\d+)?%?){2}(?:\s*\/\s*[\d.]+%?)?$`, // channel triplet
    String.raw`^#[0-9a-fA-F]{3,8}$`,
    String.raw`^(?:rgba?|hsla?)\(.*\)$`,
  ].join("|"),
);
const FONT_SIZE_NAME = /^--(?:font-size|fs|text)(?:-|$)/;
const LENGTH_VALUE = /^-?\d*\.?\d+(?:px|rem|em)$/;

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "");

/** Returns the body of the first top-level-ish block whose selector is exactly `selector`. */
function blockBody(css, selector) {
  const re = new RegExp(`(^|[{};\\s])${selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\s*\\{`, "g");
  const m = re.exec(css);
  if (!m) return null;
  let depth = 1;
  const start = m.index + m[0].length;
  for (let i = start; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) return css.slice(start, i);
  }
  throw new Error(`unterminated "${selector}" block`);
}

export function isTokenDeclaration(name, value) {
  if (FONT_SIZE_NAME.test(name)) return LENGTH_VALUE.test(value);
  return COLOUR_VALUE.test(value);
}

/** Parses `--name: value;` declarations; a later duplicate replaces the earlier one in place. */
export function parseDeclarations(body) {
  const out = new Map();
  for (const m of body.matchAll(/(--[A-Za-z0-9_-]+)\s*:\s*([^;]+);/g)) {
    const value = m[2].trim().replace(/\s+/g, " ");
    if (isTokenDeclaration(m[1], value)) out.set(m[1], value);
  }
  return out;
}

export function parseTokens(indexCss) {
  const css = stripComments(indexCss);
  const root = blockBody(css, ":root");
  const dark = blockBody(css, ".dark");
  if (root === null) throw new Error("no :root block found in index.css");
  if (dark === null) throw new Error("no .dark block found in index.css");
  return { light: parseDeclarations(root), dark: parseDeclarations(dark) };
}

const render = (selector, map) =>
  `${selector} {\n${[...map].map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;

export function renderTokensCss(indexCss) {
  const { light, dark } = parseTokens(indexCss);
  return (
    "/* Copyright 2026 SK Telecom Co., Ltd. */\n" +
    "/* SPDX-License-Identifier: Apache-2.0 */\n" +
    "/* GENERATED by docker/web/frontend/scripts/build-tokens.mjs from src/index.css. */\n" +
    "/* Do not edit: run `npm run tokens:build` in docker/web/frontend. */\n\n" +
    render(":root", light) +
    "\n" +
    render(".dark", dark)
  );
}
